import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const SOURCE_SKILLS_DIR = path.join(".agents", "skills");
export const CLAUDE_SKILLS_DIR = path.join(".claude", "skills");

function readFrontmatter(source, file) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(source);
  if (!match) {
    throw new Error(`Missing frontmatter in ${file}`);
  }
  const fields = Object.fromEntries(match[1].split(/\r?\n/).map((line) => {
    const separator = line.indexOf(":");
    return [line.slice(0, separator).trim(), line.slice(separator + 1).trim()];
  }));
  if (!fields.name || !fields.description) {
    throw new Error(`Missing name or description in ${file}`);
  }
  return fields;
}

export function buildClaudeSkillWrappers(root) {
  const sourceDir = path.join(root, SOURCE_SKILLS_DIR);
  return readdirSync(sourceDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
    .map((skillName) => {
      const sourcePath = `.agents/skills/${skillName}/SKILL.md`;
      const { name, description } = readFrontmatter(readFileSync(path.join(root, sourcePath), "utf8"), sourcePath);
      if (name !== skillName) {
        throw new Error(`Skill name ${name} does not match its directory ${skillName}`);
      }
      const content = [
        "---",
        `name: ${name}`,
        `description: ${description}`,
        "---",
        "",
        `<!-- Generated by \`npm run agents:sync\` from ${sourcePath}. Do not edit. -->`,
        "",
        `This skill is maintained in \`${sourcePath}\`. Read that file now and follow it completely. Its paths are relative to the repository root.`,
        ""
      ].join("\n");
      return { name, path: path.join(CLAUDE_SKILLS_DIR, name, "SKILL.md"), content };
    });
}

function syncClaudeSkills(root) {
  const wrappers = buildClaudeSkillWrappers(root);
  const targetDir = path.join(root, CLAUDE_SKILLS_DIR);
  const expected = new Set(wrappers.map((wrapper) => wrapper.name));
  if (existsSync(targetDir)) {
    for (const entry of readdirSync(targetDir, { withFileTypes: true })) {
      if (entry.isDirectory() && !expected.has(entry.name)) {
        rmSync(path.join(targetDir, entry.name), { recursive: true });
      }
    }
  }
  for (const wrapper of wrappers) {
    mkdirSync(path.dirname(path.join(root, wrapper.path)), { recursive: true });
    writeFileSync(path.join(root, wrapper.path), wrapper.content, "utf8");
  }
  console.log(`Synced ${wrappers.length} Claude Code skill wrappers.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  syncClaudeSkills(path.resolve(path.dirname(fileURLToPath(import.meta.url)), ".."));
}
